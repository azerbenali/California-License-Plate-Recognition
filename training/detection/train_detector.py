"""Train the plate detector: a YOLO pose model with 1 class (plate) and
4 keypoints (the plate corners TL, TR, BR, BL), then export it to ncnn.

    python -m training.detection.train_detector --data data/det --epochs 150
    python -m training.detection.train_detector --export runs/detector/train/weights/best.pt

Dataset layout (standard YOLO pose format):

    data/det/images/train/*.jpg     data/det/labels/train/*.txt
    data/det/images/val/*.jpg       data/det/labels/val/*.txt

One line per plate, all values normalized to 0..1:

    0 cx cy w h  x_tl y_tl 2  x_tr y_tr 2  x_br y_br 2  x_bl y_bl 2

(the third number of each corner is visibility: 2 = visible, 1 = occluded,
0 = not labeled).
"""
from __future__ import annotations

import argparse
from pathlib import Path

from ..common import config as C

YAML_TEMPLATE = """# generated by train_detector.py
path: {root}
train: images/train
val: images/val
kpt_shape: [{k}, 3]
flip_idx: [1, 0, 3, 2]   # horizontal flip swaps TL<->TR and BR<->BL
names:
  0: plate
"""


def write_yaml(root: Path, out_dir: Path) -> Path:
    for sub in ("images/train", "images/val", "labels/train", "labels/val"):
        if not (root / sub).is_dir():
            raise SystemExit(f"Missing folder: {root / sub}")
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "plates.yaml"
    path.write_text(YAML_TEMPLATE.format(root=root.resolve().as_posix(), k=C.DET_NUM_KEYPOINTS))
    return path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", help="dataset root (see layout above)")
    ap.add_argument("--model", default="yolo11n-pose.pt",
                    help="starting weights; yolo11n-pose.pt gives the classic output layout")
    ap.add_argument("--epochs", type=int, default=150)
    ap.add_argument("--batch", type=int, default=16)
    ap.add_argument("--imgsz", type=int, default=C.DET_INPUT_SIZE)
    ap.add_argument("--device", default=None, help="e.g. 0 for the first GPU, mps, cpu")
    ap.add_argument("--workers", type=int, default=4, help="data loading workers")
    ap.add_argument("--project", default="runs/detector")
    ap.add_argument("--export", default="", help="skip training; export these weights to ncnn")
    args = ap.parse_args()

    from ultralytics import YOLO  # pip install ultralytics

    weights = args.export
    if not weights:
        if not args.data:
            raise SystemExit("--data is required for training")
        # Absolute project path: recent versions put relative ones
        # under runs/<task>/.
        project = Path(args.project).resolve()
        yaml_path = write_yaml(Path(args.data), project)
        model = YOLO(args.model)
        model.train(data=str(yaml_path), epochs=args.epochs, batch=args.batch,
                    imgsz=args.imgsz, device=args.device, project=str(project),
                    name="train", exist_ok=True, workers=args.workers,
                    degrees=5.0, perspective=0.0005, fliplr=0.5, mosaic=1.0)
        weights = str(model.trainer.best)  # where this version saved it

    # Fixed input size: the C++ detector letterboxes to the same square.
    out = YOLO(weights).export(format="ncnn", imgsz=args.imgsz, half=True)  # fp16 storage
    print(f"ncnn detector exported to: {out}")
    print("Use model.ncnn.param / model.ncnn.bin from that folder with "
          "--det-param / --det-bin (blobs in0 -> out0).")


if __name__ == "__main__":
    main()
